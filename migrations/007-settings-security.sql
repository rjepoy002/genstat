CREATE TABLE IF NOT EXISTS genstat_settings_security (
    ID TINYINT UNSIGNED NOT NULL PRIMARY KEY,
    PINHash VARCHAR(255) NOT NULL,
    FailedAttempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
    LockedUntil BIGINT UNSIGNED NOT NULL DEFAULT 0,
    PINVersion BIGINT UNSIGNED NOT NULL DEFAULT 1,
    CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT genstat_settings_singleton CHECK (ID = 1)
) ENGINE=InnoDB;
